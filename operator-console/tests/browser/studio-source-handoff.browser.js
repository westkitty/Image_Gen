'use strict';
// Library -> 3D / World handoffs retain exact selected canonical ID, never a newer run.
const assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
const {startServer,launchBrowser,installImageFixtures,runCleanups, openStudio }=require('./helpers');
(async()=>{
 const id='fixture-library-older.png';
 const {base}=await startServer();const browser=await launchBrowser(chromium);const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await installImageFixtures(page,{[id]:{w:640,h:480,meta:{target:'sd15',seed:71}}});
 await page.route('**/api/**',r=>['GET','HEAD'].includes(r.request().method())?r.fallback():r.fulfill({status:409,json:{error:'read-only fixture'}}));
 await page.route('**/api/library/images**',r=>r.fulfill({json:{total:1,items:[{id,url:'/api/images/'+id,thumbnailUrl:'/api/images/'+id,width:640,height:480,meta:{target:'sd15',seed:71}}]}}));
 await openStudio(page, base+'/dexdiffusion/',{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>window.__dex?.state?.version===2,{timeout:15000});
 await page.evaluate(()=>__dex.setState({runs:[{id:'recent-different-run',imageFile:'fixture-newest.png',model:'sd15'}]}));
 await page.locator('[data-studio-category="library"]').click();
 const selected=page.getByRole('button',{name:'Select '+id+' for details'});
 await selected.waitFor({state:'visible',timeout:12000});await selected.click();
 const actions=page.locator('[data-library-primary-actions="'+id+'"]');
 await actions.waitFor({state:'visible',timeout:6000});
 const download=actions.getByRole('link',{name:'Download selected image'});
 assert.equal(await download.getAttribute('download'),id);
 assert.match(await download.getAttribute('href'),/\/api\/images\/fixture-library-older\.png\/export$/);
 await actions.getByRole('button',{name:'Use for 3D'}).click();
 await page.waitForFunction(id=>__dex.state.screens[2]==='3d' && __dex.state.asset3dSourceArtifact===id,id);
 const source3d=page.getByRole('combobox',{name:'3D source image'});
 await source3d.waitFor({state:'visible'});
 await page.waitForFunction(id=>document.querySelector('select[aria-label=\"3D source image\"]')?.value===id,id,{timeout:6000});
 assert.equal(await source3d.inputValue(),id,'3D receives the older exact Library image');
 assert.ok(await source3d.locator('option[value="'+id+'"]').count(), '3D must show selected source even if not in recent runs');
 await page.locator('[data-studio-category="library"]').click();
 const actionsAgain=page.locator('[data-library-primary-actions="'+id+'"]');
 await actionsAgain.waitFor({state:'visible'});
 await actionsAgain.getByRole('button',{name:'Use for World'}).click();
 await page.waitForFunction(id=>__dex.state.screens[2]==='world'&&__dex.state.worldSourceArtifact===id,id);
 const worldSource=page.getByRole('combobox',{name:'World source image'});
 await worldSource.waitFor({state:'visible'});
 await page.waitForFunction(id=>document.querySelector('select[aria-label=\"World source image\"]')?.value===id,id,{timeout:6000});
 assert.equal(await worldSource.inputValue(),id,'World receives the older exact Library image');
 assert.equal(await page.evaluate(()=>__dex.state.activeAssetSelection.id),id);
 assert.deepEqual(errors,[]);
 console.log('[studio-source-handoff.browser] PASS LIBRARY_HANDOFF_PASS',JSON.stringify({source:id,createdRun:'fixture-newest.png',source3d:'exact',world:'exact',download:true}));
})().catch(e=>{console.error('LIBRARY_HANDOFF_FAIL',e.stack);process.exitCode=1}).finally(runCleanups);
